// Chinese is the source of truth: it is the default language, so it is the text
// that gets read most and reviewed first. English is typed against it, which
// makes a missing translation a compile error rather than a blank in the window.
//
// What is deliberately *not* translated: the daemon's own vocabulary. Statuses
// (RUNNING, HEALTHY, BOUND), error codes (PROJECT_UNTRUSTED) and the messages the
// daemon produces stay as they are, because they are the same tokens `--json` and
// the CLI use — a developer searching the docs for "BLOCKED" must find the same
// word here. Where a token needs explaining, the gloss goes in its tooltip.

